import { describe, expect, test } from "bun:test";
import rules from "../src/lib/plotting/ai/templates/beautify-image.txt?raw";

describe("обязательные условия рисовки", () => {
  test("фотореалистичность исключена", () => {
    expect(rules).toContain("Не используй фотореалистичность");
  });
  test("мультяшный стиль предпочтителен", () => {
    expect(rules).toContain("Отдавай предпочтение мультяшному стилю");
  });
  test("оформление использует пастельные тона", () => {
    expect(rules).toContain("Используй пастельные тона в художественном оформлении");
  });
  test("без запроса надписей добавляется минимум текста", () => {
    expect(rules).toContain("Если пользователь явно не просит надписи, добавляй минимум надписей");
  });
  test("словесные надписи только на русском, математическая запись сохраняется", () => {
    expect(rules).toContain("Все словесные надписи обязательно только на русском языке");
    expect(rules).toContain("Формулы и математические обозначения");
    expect(rules).toContain("сохраняй в исходной записи");
  });
});